"""Conditional echo-record shares for crystal covers G = Z^n (batch 09).

Model (sketch): static flat torus R^n/Gamma, Gamma a finite-index sublattice of Z^n,
observer at rest at the origin, beacon on from t=0, c=1.  The echo via deck element g
first arrives at proper time |g|_2.  Record at time tau: R_tau(Gamma) = {g in Gamma\\{0}: |g| <= tau}
(exact vectors: a fixed frame; this is the non-lossy record, cf. #355 on the isotropy gauge).
Subgroups enumerated by Hermite normal form (rows lower-triangular).
"""
import itertools, math, sys
from collections import Counter, defaultdict

def hnf_subgroups(n, N):
    """All index<=N sublattices of Z^n as lower-triangular HNF row bases."""
    out = []
    def rec(rows, i, idx):
        if i == n:
            out.append(tuple(rows)); return
        for d in range(1, N // idx + 1):
            # row i: (x_0..x_{i-1}, d, 0..0) with 0 <= x_j < diag_j
            diags = [rows[j][j] for j in range(i)]
            for xs in itertools.product(*[range(a) for a in diags]):
                row = list(xs) + [d] + [0] * (n - i - 1)
                rec(rows + [tuple(row)], i + 1, idx * d)
    rec([], 0, 1)
    return out

def index(B): return math.prod(B[i][i] for i in range(len(B)))

def member(B, v):
    n = len(B); v = list(v)
    for i in range(n - 1, -1, -1):
        if v[i] % B[i][i]: return False
        c = v[i] // B[i][i]
        for j in range(n): v[j] -= c * B[i][j]
    return all(x == 0 for x in v)

def ball(n, tau):
    r = int(math.floor(tau))
    return [v for v in itertools.product(range(-r, r + 1), repeat=n)
            if any(v) and sum(x * x for x in v) <= tau * tau + 1e-9]

def record(B, pts): return frozenset(v for v in pts if member(B, v))

def word_len_ok(B, L):
    """Gamma generated by elements of L1-norm <= L (generators e_i named)."""
    n = len(B)
    gens = [v for v in itertools.product(range(-L, L + 1), repeat=n)
            if any(v) and sum(map(abs, v)) <= L and member(B, v)]
    # index of sublattice generated by gens equals index(B)?  compute via gcd of n x n minors
    if len(gens) < n: return False
    g = 0
    for S in itertools.combinations(gens, n):
        d = abs(round(det(S)))
        g = math.gcd(g, d)
        if g == index(B): return True
    return g == index(B)

def det(M):
    M = [list(map(float, r)) for r in M]; n = len(M); d = 1.0
    for i in range(n):
        p = max(range(i, n), key=lambda r: abs(M[r][i]))
        if abs(M[p][i]) < 1e-12: return 0.0
        if p != i: M[i], M[p] = M[p], M[i]; d = -d
        d *= M[i][i]
        for r in range(i + 1, n):
            f = M[r][i] / M[i][i]
            for c in range(i, n): M[r][c] -= f * M[i][c]
    return d

def covering_radius_2d(B):
    # Gauss-reduce, then circumradius of triangle (0,a,b) with acute reduced basis
    a, b = list(B[0]), list(B[1])
    dot = lambda x, y: x[0]*y[0] + x[1]*y[1]
    while True:
        if dot(a, a) > dot(b, b): a, b = b, a
        m = round(dot(a, b) / dot(a, a))
        if m == 0: break
        b = [b[0] - m*a[0], b[1] - m*a[1]]
    if dot(a, b) < 0: b = [-b[0], -b[1]]
    c = [b[0]-a[0], b[1]-a[1]]
    la, lb, lc = map(lambda x: math.sqrt(dot(x, x)), (a, b, c))
    area = abs(a[0]*b[1] - a[1]*b[0]) / 2
    return la * lb * lc / (4 * area)

def shares(subs, tau, tau2, n):
    p1, p2 = ball(n, tau), ball(n, tau2)
    by = defaultdict(Counter)
    for B in subs:
        by[record(B, p1)][record(B, p2)] += 1
    return by

def show(by, label, maxrows=6):
    print(f"--- {label}")
    rows = sorted(by.items(), key=lambda kv: -sum(kv[1].values()))[:maxrows]
    for R, ctr in rows:
        tot = sum(ctr.values())
        top = sorted(ctr.items(), key=lambda kv: -kv[1])
        desc = ", ".join(f"{len(R2)-len(R):+d} new: {c/tot:.3f}" for R2, c in top[:4])
        print(f"  record |R|={len(R)} (n_worlds={tot}): {desc}")

if __name__ == "__main__":
    for n, Ns, tau, tau2 in [(2, [20, 40, 80], 1.0, 2.0), (3, [10, 20, 30], 1.0, 1.5)]:
        print(f"===== Z^{n}, tau={tau} -> tau'={tau2}, index cutoff")
        for N in Ns:
            subs = hnf_subgroups(n, N)
            by = shares(subs, tau, tau2, n)
            show(by, f"N={N}, #subgroups={len(subs)}")
    # full-rank conditioning: record already spans a full-rank lattice
    print("===== Z^2, condition on full-rank record at tau=2 (contains (2,0),(0,2))")
    for N in [8, 16, 64]:
        subs = [B for B in hnf_subgroups(2, N)]
        by = shares(subs, 2.0, 3.0, 2)
        for R, ctr in by.items():
            if (2, 0) in R and (0, 2) in R and len(R) == 4 and (1, 1) not in R and (1,0) not in R:
                tot = sum(ctr.values())
                print(f"  N={N}: record R={sorted(R)} worlds={tot}: " +
                      ", ".join(f"{sorted(set(R2)-set(R))}: {c}/{tot}" for R2, c in ctr.items()))
    # listing comparison in Z^2: index vs covering radius (diameter proxy) vs word length
    print("===== Z^2 listing comparison, tau=1 -> 2, share of 'no new echo' given empty record")
    allsubs = hnf_subgroups(2, 400)
    p1, p2 = ball(2, 1.0), ball(2, 2.0)
    def share_empty(subs):
        e = [B for B in subs if not record(B, p1)]
        if not e: return None, 0
        same = sum(1 for B in e if not record(B, p2))
        return same / len(e), len(e)
    for N in [25, 100, 400]:
        print("  index<=%d: share=%.3f (n=%d)" % ((N,) + share_empty([B for B in allsubs if index(B) <= N])))
    for D in [3, 6, 10]:
        sub = [B for B in allsubs if covering_radius_2d(B) <= D]
        print("  covering radius<=%d: share=%.3f (n=%d)" % ((D,) + share_empty(sub)))
    for Lw in [4, 8, 12]:
        sub = [B for B in allsubs if word_len_ok(B, Lw)]
        print("  word length<=%d: share=%.3f (n=%d)" % ((Lw,) + share_empty(sub)))
